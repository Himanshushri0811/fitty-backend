from rest_framework.views import APIView
from rest_framework.response import Response
from rest_framework.permissions import AllowAny, IsAuthenticated
from .models import ContactMessage, LiveChatSession
from .serializers import ContactMessageSerializer
from datetime import datetime

from common.utils import send_contact_email

class ContactMessageView(APIView):
    permission_classes = [AllowAny]

    def post(self, request):
        serializer = ContactMessageSerializer(data=request.data)
        if serializer.is_valid():
            contact_msg = serializer.save()
            
            # Send Email Notification
            try:
                send_contact_email(
                    subject=contact_msg.subject,
                    message=contact_msg.message,
                    email=contact_msg.email,
                    name=contact_msg.name
                )
            except Exception as e:
                print(f"Failed to send contact email: {e}")
                
            return Response({"message": "Message sent successfully!"}, status=201)
        return Response(serializer.errors, status=400)

class PublicLiveChatView(APIView):
    permission_classes = [AllowAny]

    def post(self, request):
        """
        Visitor sends a message.
        Requires 'visitor_id' (generated by frontend if not logged in).
        """
        visitor_id = request.data.get('visitor_id')
        message = request.data.get('message')
        visitor_name = request.data.get('visitor_name', 'Guest')
        
        if not visitor_id or not message:
            return Response({"error": "Missing visitor_id or message"}, status=400)
            
        # Find or Create Session
        session = LiveChatSession.objects(visitor_id=visitor_id, status='active').first()
        if not session:
            session = LiveChatSession(visitor_id=visitor_id, visitor_name=visitor_name)
            session.save()
            
        session.add_message('visitor', message)
        
        return Response({
            "status": "sent",
            "session_id": str(session.id),
            "messages": [{"sender": m.sender, "content": m.content, "timestamp": m.timestamp} for m in session.messages]
        })

    def get(self, request):
        """
        Poll for new messages.
        """
        visitor_id = request.query_params.get('visitor_id')
        if not visitor_id:
            return Response({"error": "Missing visitor_id"}, status=400)
            
        session = LiveChatSession.objects(visitor_id=visitor_id, status='active').first()
        if not session:
             return Response({"messages": []})
             
        return Response({
            "messages": [{"sender": m.sender, "content": m.content, "timestamp": m.timestamp} for m in session.messages]
        })

class AgentLiveChatView(APIView):
    permission_classes = [IsAuthenticated]
    
    def get(self, request):
        """
        Get all active sessions (Inbox for Gym Owner)
        """
        # In a multi-tenant app, we'd filter by gym_id. 
        # For now, assuming Global Admin or Single Gym context for simplicity of this demo,
        # OR robustly, we link sessions to a Gym if we knew which gym the visitor is on.
        # But visitors are usually on the landing page.
        # Let's return ALL active sessions for any Gym Owner for now (Simulated Support Team).
        
        if request.user.role != 'GYM_OWNER' and not request.user.is_staff:
             return Response({"error": "Unauthorized"}, status=403)
             
        sessions = LiveChatSession.objects(status='active').order_by('-updated_at')
        
        data = []
        for s in sessions:
            data.append({
                "id": str(s.id),
                "visitor_name": s.visitor_name,
                "unread_count": s.unread_count,
                "last_message": s.messages[-1].content if s.messages else "",
                "updated_at": s.updated_at,
                "messages": [{"sender": m.sender, "content": m.content, "timestamp": m.timestamp} for m in s.messages]
            })
            
        return Response(data)

    def post(self, request):
        """
        Agent replies to a session
        """
        session_id = request.data.get('session_id')
        message = request.data.get('message')
        
        if not session_id or not message:
            return Response({"error": "Missing data"}, status=400)
            
        session = LiveChatSession.objects(id=session_id).first()
        if not session:
            return Response({"error": "Session not found"}, status=404)
            
        session.add_message('agent', message)
        # Reset unread count since agent reviewed it (implied)
        session.unread_count = 0 
        session.save()
        
        return Response({"status": "sent", "messages": [{"sender": m.sender, "content": m.content} for m in session.messages]})
